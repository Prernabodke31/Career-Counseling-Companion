import { useState, useEffect } from 'react'
import api from '../api'
import toast from 'react-hot-toast'
import ReactMarkdown from 'react-markdown'

export default function CareerPlan() {
  const [loading, setLoading] = useState(false)
  const [plans, setPlans] = useState([])
  const [activePlan, setActivePlan] = useState(null)
  const [gapForm, setGapForm] = useState({ career: '', result: null, loading: false })

  useEffect(() => {
    api.get('/career/plans').then(({ data }) => {
      setPlans(data)
      if (data.length) setActivePlan(data[0])
    })
  }, [])

  const generatePlan = async () => {
    setLoading(true)
    try {
      const { data } = await api.post('/career/recommend')
      toast.success('Career plan generated by IBM Granite!')
      const all = await api.get('/career/plans')
      setPlans(all.data)
      setActivePlan({ ...all.data[0], full_plan: data.full_plan, reasoning: data.raw_response })
    } catch (err) {
      toast.error(err.response?.data?.detail || 'Failed to generate plan.')
    } finally {
      setLoading(false)
    }
  }

  const analyzeGap = async () => {
    if (!gapForm.career.trim()) { toast.error('Enter a career to analyze.'); return }
    setGapForm(f => ({ ...f, loading: true, result: null }))
    try {
      const { data } = await api.post('/career/skills-gap', { target_career: gapForm.career })
      setGapForm(f => ({ ...f, result: data, loading: false }))
    } catch { toast.error('Analysis failed.'); setGapForm(f => ({ ...f, loading: false })) }
  }

  return (
    <div className="page-content">
      <div className="section-header">
        <h2 className="section-title">AI Career Recommendations</h2>
        <button className="btn btn-primary" onClick={generatePlan} disabled={loading}>
          {loading ? <><span className="spinner" /> Analyzing with IBM Granite…</> : '🤖 Generate New Plan'}
        </button>
      </div>

      <div className="alert alert-info" style={{ marginBottom: 20 }}>
        IBM Granite analyzes your academic profile, assessment scores, and real-time labor market data to generate personalized career pathway recommendations.
      </div>

      {plans.length === 0 && !loading && (
        <div className="empty-state card">
          <h3>No career plans yet</h3>
          <p>Click "Generate New Plan" to let IBM Granite analyze your profile and suggest the best career paths for you.</p>
        </div>
      )}

      {/* Plan History Tabs */}
      {plans.length > 0 && (
        <div style={{ display: 'flex', gap: 8, marginBottom: 16, flexWrap: 'wrap' }}>
          {plans.map((p, i) => (
            <button key={p.plan_id} onClick={() => setActivePlan(p)}
              className={`btn btn-sm ${activePlan?.plan_id === p.plan_id ? 'btn-primary' : 'btn-secondary'}`}>
              Plan {plans.length - i} · {new Date(p.generated_at).toLocaleDateString()}
            </button>
          ))}
        </div>
      )}

      {activePlan && (
        <>
          {/* Recommended Careers */}
          {activePlan.recommended_careers?.length > 0 && (
            <div className="card" style={{ marginBottom: 16 }}>
              <div className="card-title">🎯 Recommended Career Pathways</div>
              {activePlan.recommended_careers.map((career, i) => (
                <div key={i} style={{
                  padding: '12px', marginBottom: 8,
                  background: 'var(--surface-1)', borderRadius: 6,
                  borderLeft: '3px solid var(--ibm-blue)'
                }}>
                  <span style={{ fontWeight: 500 }}>{i + 1}. {career}</span>
                </div>
              ))}
            </div>
          )}

          {/* Action Steps */}
          {activePlan.action_steps?.length > 0 && (
            <div className="card" style={{ marginBottom: 16 }}>
              <div className="card-title">📋 Personalized Action Plan</div>
              <ol style={{ paddingLeft: 20, lineHeight: 2 }}>
                {activePlan.action_steps.map((step, i) => (
                  <li key={i} style={{ fontSize: '0.875rem', color: 'var(--text-secondary)' }}>{step}</li>
                ))}
              </ol>
            </div>
          )}

          {/* Full Granite Response */}
          <div className="card" style={{ marginBottom: 16 }}>
            <div className="card-title">📝 Full IBM Granite Analysis</div>
            <div style={{
              fontSize: '0.875rem', lineHeight: 1.8,
              background: 'var(--surface-1)', padding: 16, borderRadius: 6,
              maxHeight: 500, overflowY: 'auto',
            }}>
              <ReactMarkdown>
                {activePlan.reasoning || activePlan.full_plan || 'Analysis not available.'}
              </ReactMarkdown>
            </div>
          </div>

          {/* Market Outlook */}
          {activePlan.market_outlook && Object.keys(activePlan.market_outlook).length > 0 && (
            <div className="card" style={{ marginBottom: 16 }}>
              <div className="card-title">📊 Market Outlook</div>
              <div className="tags-wrap">
                {Object.entries(activePlan.market_outlook).map(([sector, growth]) => (
                  <span key={sector} className="tag tag-green">
                    {sector}: {growth}
                  </span>
                ))}
              </div>
            </div>
          )}
        </>
      )}

      {/* Skills Gap Analyzer */}
      <div className="card">
        <div className="card-title">🔍 Skills Gap Analyzer</div>
        <p style={{ fontSize: '0.85rem', color: 'var(--text-muted)', marginBottom: 12 }}>
          Enter a target career to get a personalized gap analysis powered by IBM Granite.
        </p>
        <div style={{ display: 'flex', gap: 10, marginBottom: 12 }}>
          <input className="form-input" style={{ flex: 1 }} placeholder="e.g. Data Scientist, Cybersecurity Analyst"
            value={gapForm.career} onChange={e => setGapForm(f => ({ ...f, career: e.target.value }))} />
          <button className="btn btn-primary btn-sm" onClick={analyzeGap} disabled={gapForm.loading}>
            {gapForm.loading ? <span className="spinner" /> : 'Analyze'}
          </button>
        </div>
        {gapForm.result && (
          <div style={{
            background: 'var(--surface-1)', padding: 16, borderRadius: 6,
            fontSize: '0.875rem', lineHeight: 1.8,
          }}>
            <ReactMarkdown>{gapForm.result.analysis}</ReactMarkdown>
          </div>
        )}
      </div>
    </div>
  )
}
